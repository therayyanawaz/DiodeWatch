"""Pin the environment the suite is verified on, and check the pin offline.

`requirements.txt` states floors (`pandas>=2.2`), which is right for CI: a floor
install on a fresh interpreter surfaces a dependency that broke an API, and that
is a bug worth finding the day it happens. It is wrong for a host that has to come
up identically twice, because a fresh resolve is not byte-identical across days.

This script produces the other artefact, `requirements.lock`: exact versions for
everything the verified run imported, in a form pip consumes directly.

    python scripts/checks/make_lock.py                  # exact versions
    python scripts/checks/make_lock.py --hashes         # plus SHA256 per file
    pip install -r requirements.lock                    # the pinned path

`--check` verifies the lock without touching the network: every requirement in
`requirements.txt` appears, every entry is pinned to an exact version, and no
distribution is listed twice. CI runs it, so the lock cannot rot into a file that
looks pinned and is not. A test asserts the checker fails on each of those three
faults, because a guard that has never failed is a guard nobody has tested.

**On hashes.** `--hashes` asks the index for every file it publishes for that
exact version, and pip then refuses a substituted artefact. It only works when the
index serves the pinned version; a version that exists only in this project's own
timeline is reported by name rather than given a fabricated digest, and the entry
is written without hashes so the file stays installable. Run it with
`pip install --require-hashes -r requirements.lock` once every line carries one.
"""
from __future__ import annotations

import argparse
import json
import platform
import re
import shutil
import subprocess
import sys
import urllib.request
from importlib import metadata
from pathlib import Path
from typing import Any

REPO = Path(__file__).resolve().parents[2]
REQUIREMENTS = REPO / "requirements.txt"
PINNED = re.compile(r"^\s*([A-Za-z0-9][A-Za-z0-9._-]*)\s*(?:==\s*([^\s;#]+))?")
LOCK_ENTRY = re.compile(r"^([A-Za-z0-9][A-Za-z0-9._-]*)==(\S+)\s*\\?$")
HASH_LINE = re.compile(r"^\s+--hash=sha256:([0-9a-f]{64})\s*\\?$")


def requirement_names() -> list[str]:
    names = []
    for line in REQUIREMENTS.read_text(encoding="utf-8").splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        match = PINNED.match(line)
        if match:
            names.append(match.group(1).lower().replace("_", "-"))
    return names


def _get_json(url: str) -> dict[str, Any]:
    """Fetch one index document, via curl when it is available.

    A host behind a TLS-inspecting proxy has a certificate chain `urllib` refuses
    by default; `curl` uses the system trust store and works there. Falling back
    to `urllib` keeps the script usable on a minimal image."""
    curl = shutil.which("curl")
    if curl:
        # Index documents are UTF-8; a Windows console default (cp1252) mangles
        # them into a decode error, so the encoding is stated, not inherited.
        proc = subprocess.run([curl, "-fsSL", "--max-time", "30", url],
                              capture_output=True, text=True, timeout=60,
                              encoding="utf-8", errors="replace", check=False)
        if proc.returncode == 0 and (proc.stdout or "").strip():
            return json.loads(proc.stdout)
    with urllib.request.urlopen(url, timeout=30) as resp:  # fixed host
        return json.load(resp)


def _hashes(name: str, version: str) -> list[str]:
    """Every SHA256 the index publishes for one release, or [] when it cannot say.

    An empty list is the honest answer for a version the index does not serve;
    inventing a digest would turn a missing pin into a false one."""
    try:
        doc = _get_json(f"https://pypi.org/pypi/{name}/{version}/json")
    except Exception:  # noqa: BLE001 - network and 404 both mean "cannot say"
        return []
    return sorted({f["digests"]["sha256"] for f in doc.get("urls", [])
                   if f.get("digests", {}).get("sha256")})


def installed(skip: set[str]) -> list[tuple[str, str]]:
    rows: list[tuple[str, str]] = []
    for dist in metadata.distributions():
        name = dist.metadata["Name"] if dist.metadata else None
        if not name or not dist.version:
            continue
        key = name.lower().replace("_", "-")
        if key in skip:
            continue
        rows.append((key, dist.version))
    return sorted(set(rows))


def build(skip: set[str], with_hashes: bool) -> tuple[str, list[str]]:
    missing: list[str] = []
    out = [
        "# requirements.lock, generated by scripts/checks/make_lock.py.",
        "# Do not edit by hand: re-run the script on the environment you verified.",
        f"# Source environment: Python {platform.python_version()} on {platform.platform()}",
        "#",
        "# Exact versions of everything the test suite imported. requirements.txt",
        "# keeps its floors on purpose: CI resolves fresh so a broken dependency",
        "# surfaces immediately, while a host install uses this file so it comes up",
        "# identically twice. docs/threat-model.md explains why both exist.",
        "",
    ]
    for name, version in installed(skip):
        hashes = _hashes(name, version) if with_hashes else []
        if with_hashes and not hashes:
            missing.append(f"{name}=={version}")
        if not hashes:
            out.append(f"{name}=={version}")
            continue
        out.append(f"{name}=={version} \\")
        for i, digest in enumerate(hashes):
            out.append(f"    --hash=sha256:{digest}"
                       + (" \\" if i < len(hashes) - 1 else ""))
    return "\n".join(out) + "\n", missing


def check(path: Path, require_hashes: bool = False) -> list[str]:
    """Structural verification, offline: complete, exact, unambiguous, hashed."""
    problems: list[str] = []
    if not path.exists():
        return [f"{path.name} is missing"]
    locked: dict[str, tuple[str, int]] = {}
    current: str | None = None
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        match = LOCK_ENTRY.match(line)
        if match and not line.startswith(" "):
            name = match.group(1).lower().replace("_", "-")
            if name in locked:
                problems.append(f"{name} is listed twice")
            locked[name] = (match.group(2), 0)
            current = name
            continue
        hash_match = HASH_LINE.match(line)
        if hash_match and current:
            version, count = locked[current]
            locked[current] = (version, count + 1)
            continue
        problems.append(f"unrecognised line: {line[:60]}")

    for name, (version, hashes) in locked.items():
        if not version or version in {"*", "latest"}:
            problems.append(f"{name} is not pinned to an exact version")
        if require_hashes and hashes == 0:
            problems.append(f"{name} carries no hash")

    for name in requirement_names():
        if name not in locked:
            problems.append(f"{name} is required but not locked")
    return problems


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        description="Pin the verified environment to exact versions")
    ap.add_argument("--out", default=str(REPO / "requirements.lock"))
    ap.add_argument("--check", action="store_true",
                    help="verify the lock offline instead of writing it")
    ap.add_argument("--hashes", action="store_true",
                    help="also record the SHA256 of every published file")
    ap.add_argument("--require-hashes", action="store_true",
                    help="with --check: every entry must carry a hash")
    ap.add_argument("--skip", default="pip,setuptools,wheel",
                    help="comma-separated distributions to leave out")
    args = ap.parse_args(argv)

    if args.check:
        problems = check(Path(args.out), args.require_hashes)
        for problem in problems:
            print(f"FAIL {problem}", file=sys.stderr)
        if problems:
            return 1
        extra = " with hashes" if args.require_hashes else ""
        print(f"lock OK: every requirement pinned{extra}")
        return 0

    text, missing = build({s.strip().lower().replace("_", "-")
                           for s in args.skip.split(",") if s.strip()},
                          args.hashes)
    target = Path(args.out)
    target.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {target}")
    if missing:
        print(f"note: {len(missing)} version(s) are not served by the index, so "
              f"they are pinned without hashes:", file=sys.stderr)
        for name in missing:
            print(f"  {name}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
